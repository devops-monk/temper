"""Reinforcement learning on Apple Silicon: GRPO, Dr. GRPO and DAPO as LoRA adapters, with MLX.

Each step takes a batch of prompts, has the model write `generations` replies to each (sampled, with
mlx-lm's batch generation), scores them with the run's rewards (rewards.py), and makes the replies that
scored above their group's average likelier and the ones below less likely. Replies are generated by the
model being trained and it takes one update on them, so the policy ratio is 1 and the loss's gradient is
the advantage times each reply token's log-likelihood gradient. There's no KL penalty against the starting
model (beta 0, as Dr. GRPO and DAPO recommend), so no reference model is kept.

The objectives differ in how they scale and average (Liu et al. 2025, Yu et al. 2025):
  grpo     advantage = (reward - group mean) / group std; loss averaged over each reply's tokens, then replies
  dr_grpo  advantage = reward - group mean; loss summed over tokens and divided by a constant (the
           completion limit), which removes GRPO's bias towards long wrong replies and easy questions
  dapo     advantage as GRPO; loss averaged over every token in the batch; groups whose replies all scored
           the same (no signal) are left out

Adapters are saved as mlx-lm saves them, so chat, checkpoints and export work as for fine-tuning.
"""

from __future__ import annotations

import json
import random
import time
from pathlib import Path
from typing import Callable

import mlx.core as mx
import mlx.nn as nn
import mlx.optimizers as optim
from mlx.utils import tree_flatten, tree_map

from . import chat_render
from .mlx_pref import LORA_LAYERS
from .rewards import expected, scorer

Prompt = tuple[list[dict], dict]  # prompt turns and the dataset row
EVAL_PROMPTS = 8


def prompt_ids(tokenizer, turns: list[dict]) -> list[int]:
    """The prompt as the model sees it at inference, ready for its reply. Thinking is off: it reasons in the reply."""
    text = tokenizer.apply_chat_template(turns, add_generation_prompt=True, tokenize=False, enable_thinking=False)
    return tokenizer.encode(text, add_special_tokens=False)


def advantages(rewards: list[float], group: int, objective: str) -> tuple[list[float], list[bool]]:
    """Each reply's advantage over its group, and which groups carry a signal (not all the same reward)."""
    out, useful = [], []
    for g in range(0, len(rewards), group):
        r = rewards[g : g + group]
        mean = sum(r) / len(r)
        std = (sum((x - mean) ** 2 for x in r) / max(len(r) - 1, 1)) ** 0.5
        scale = 1.0 if objective == "dr_grpo" else std + 1e-4
        out += [(x - mean) / scale for x in r]
        useful.append(max(r) > min(r))
    return out, useful


def token_logps(model, ids: mx.array, lengths: mx.array, starts: mx.array) -> tuple[mx.array, mx.array]:
    """Per-token log-likelihoods of each sequence's reply tokens, and the mask of which are reply tokens."""
    logits = model(ids[:, :-1]).astype(mx.float32)
    targets = ids[:, 1:]
    picked = mx.take_along_axis(logits, targets[..., None], axis=-1).squeeze(-1) - mx.logsumexp(logits, axis=-1)
    pos = mx.arange(targets.shape[1])[None]
    mask = (pos >= starts[:, None] - 1) & (pos < lengths[:, None] - 1)
    return picked, mask.astype(mx.float32)


def policy_loss(objective: str, logps: mx.array, mask: mx.array, adv: mx.array, denominator: float) -> mx.array:
    """The policy-gradient loss: on-policy, so exp(logp - stop_gradient(logp)) is 1 with the gradient of logp.

    Replies with no advantage are left out of `logps` (they add nothing), so the average's denominator is given:
    the number of replies (grpo), replies times the completion limit (dr_grpo), or reply tokens (dapo)."""
    per_token = -mx.exp(logps - mx.stop_gradient(logps)) * adv[:, None] * mask
    if objective == "grpo":
        return (per_token.sum(-1) / mx.maximum(mask.sum(-1), 1)).sum() / denominator
    return per_token.sum() / denominator


def denominator(objective: str, lengths: list[int], useful: list[bool], group: int, limit: int) -> float:
    """What a batch's loss is averaged over (policy_loss), counting every reply that takes part."""
    if objective == "grpo":
        return float(len(lengths))
    if objective == "dr_grpo":
        return float(len(lengths) * limit)
    return float(max(sum(n for i, n in enumerate(lengths) if useful[i // group]), 1))  # dapo: tokens of groups with a signal


def train(cfg: dict, out: Path, train_set: list[Prompt], valid_set: list[Prompt], emit: Callable[..., None], steps: int, eval_every: int, save_every: int) -> None:
    from mlx_lm import load
    from mlx_lm.generate import batch_generate
    from mlx_lm.sample_utils import make_sampler
    from mlx_lm.tuner.trainer import grad_checkpoint
    from mlx_lm.tuner.utils import linear_to_lora_layers

    objective = cfg["objective"]
    group = cfg["generations"]
    limit = cfg["max_completion_length"]
    score = scorer(cfg)

    emit("phase", name="Loading model")
    model, tokenizer = load(cfg["base_model"])
    chat_render.use(tokenizer, cfg.get("chat_template"))
    model.freeze()
    lora = {"rank": cfg["lora_r"], "scale": cfg["lora_alpha"] / cfg["lora_r"], "dropout": cfg["lora_dropout"]}
    layers = min(LORA_LAYERS, len(model.layers))
    linear_to_lora_layers(model, layers, lora)
    if cfg.get("resume_from"):
        model.load_weights(str(cfg["resume_from"]), strict=False)
    grad_checkpoint(model.layers[0])

    emit("phase", name="Preparing prompts")
    room = cfg["max_seq_length"] - limit
    encoded = [(prompt_ids(tokenizer, p), p, row) for p, row in train_set]
    encoded = [e for e in encoded if len(e[0]) <= room]
    if not encoded:
        raise ValueError(f"Every prompt is longer than the context length leaves room for ({room} tokens with {limit} for the reply). Raise the context length.")
    held = [(prompt_ids(tokenizer, p), p, row) for p, row in valid_set[:EVAL_PROMPTS]]
    eos = tokenizer.eos_token_id
    sampler = make_sampler(temp=cfg.get("temperature") or 1.0)

    def generate(items, n: int, sample=sampler) -> list[list[int]]:
        """n replies to each prompt, as token ids, ending with the end-of-sequence token when the model stopped."""
        model.eval()
        ids = [ids for ids, _, _ in items for _ in range(n)]
        replies = batch_generate(model, tokenizer, ids, max_tokens=limit, sampler=sample, return_token_ids=True).token_ids
        model.train()
        return [r + [eos] if len(r) < limit and eos is not None else r for r in replies]

    def loss_fn(model, ids, lengths, starts, adv, denom):
        logps, mask = token_logps(model, ids, lengths, starts)
        return policy_loss(objective, logps, mask, adv, denom)

    grad_fn = nn.value_and_grad(model, loss_fn)

    warmup = min(cfg["warmup_steps"], max(steps - 1, 0))
    lr = cfg["learning_rate"]
    decay = optim.linear_schedule(lr, lr * 0.1, max(steps - warmup, 1))
    schedule = optim.join_schedules([optim.linear_schedule(lr * 0.01, lr, warmup), decay], [warmup]) if warmup else decay
    opt = optim.AdamW(learning_rate=schedule, weight_decay=0.0)

    rng = random.Random(cfg["seed"])
    mx.random.seed(cfg["seed"])
    order: list[int] = []
    size = cfg["batch_size"]

    def next_batch():
        nonlocal order
        if len(order) < size:
            fresh = list(range(len(encoded)))
            rng.shuffle(fresh)
            order += fresh
        idx, order = order[:size], order[size:]
        return [encoded[i] for i in idx]

    def evaluate(step: int) -> None:
        """Greedy replies to the held-out prompts: their average reward, and a couple shown as samples."""
        if not held:
            return
        replies = generate(held, 1, sample=None)
        texts = [tokenizer.decode([t for t in r if t != eos]) for r in replies]
        rewards = [score(p, t, row) for (_, p, row), t in zip(held, texts)]
        emit("eval", step=step, val_reward=round(sum(rewards) / len(rewards), 4))
        if cfg.get("sample_replies", True):
            for (_, p, row), t, r in list(zip(held, texts, rewards))[:2]:
                emit("sample", step=step, prompt=str(p[-1]["content"])[:600], reply=t.strip()[:1200], expected=(expected(row) or "").strip()[:600], reward=r)

    adapter = out / "adapter"
    adapter.mkdir(exist_ok=True)
    (adapter / "adapter_config.json").write_text(json.dumps({
        "fine_tune_type": "lora", "num_layers": layers, "lora_parameters": lora, "model": cfg["base_model"],
        "objective": objective, "generations": group, "rewards": cfg["rewards"],
    }, indent=2))
    save = lambda path: mx.save_safetensors(str(path), dict(tree_flatten(model.trainable_parameters())))  # noqa: E731

    emit("phase", name="Training", total_steps=steps)
    model.train()
    evaluate(0)
    started = time.time()
    tokens = 0
    for step in range(1, steps + 1):
        grads, losses, all_rewards, lengths_seen, used = None, [], [], [], 0
        for _ in range(cfg["grad_accum"]):
            batch = next_batch()
            replies = generate(batch, group)
            texts = [tokenizer.decode([t for t in r if t != eos]) for r in replies]
            rewards = [score(batch[i // group][1], texts[i], batch[i // group][2]) for i in range(len(replies))]
            adv, useful = advantages(rewards, group, objective)
            all_rewards += rewards
            lengths_seen += [len(r) for r in replies]
            keep = [i for i in range(len(replies)) if useful[i // group] or objective != "dapo"]
            keep = [i for i in keep if abs(adv[i]) > 0]  # a zero advantage adds nothing to the gradient
            if not keep:
                continue
            seqs = [(batch[i // group][0] + replies[i], len(batch[i // group][0])) for i in keep]
            width = max(len(s) for s, _ in seqs)
            ids = mx.array([s + [0] * (width - len(s)) for s, _ in seqs])
            lens, starts = mx.array([len(s) for s, _ in seqs]), mx.array([st for _, st in seqs])
            tokens += int(lens.sum().item())
            denom = denominator(objective, [len(r) for r in replies], useful, group, limit)
            loss, g = grad_fn(model, ids, lens, starts, mx.array([adv[i] for i in keep]), denom)
            grads = g if grads is None else tree_map(lambda a, b: a + b, grads, g)
            mx.eval(loss, grads)
            losses.append(loss.item())
            used += 1
        if grads is not None:
            opt.update(model, tree_map(lambda x: x / used, grads))
            mx.eval(model.parameters(), opt.state)
        elapsed = time.time() - started
        mean = sum(all_rewards) / len(all_rewards)
        emit("metrics", step=step, total_steps=steps, loss=round(sum(losses) / len(losses), 4) if losses else 0.0, reward=round(mean, 4),
             reward_std=round((sum((r - mean) ** 2 for r in all_rewards) / len(all_rewards)) ** 0.5, 4),
             completion_length=round(sum(lengths_seen) / len(lengths_seen), 1), lr=float(schedule(step)),
             tokens_per_sec=round(tokens / max(elapsed, 1e-6)), eta=elapsed / step * (steps - step))
        emit("progress", value=step / steps)
        if step % eval_every == 0 or step == steps:
            evaluate(step)
        if step % save_every == 0 and step != steps:
            save(adapter / f"{step:07d}_adapters.safetensors")
    save(adapter / "adapters.safetensors")
    chat_render.save(adapter, cfg.get("chat_template"))
    emit("result", adapter=str(adapter), base_model=cfg["base_model"])
